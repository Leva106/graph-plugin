// Generates src/theme/tokens.generated.ts from the Figma variable exports in ./tokens.
// Only color tokens are kept: name ("chart/indigo/500") -> Figma variable id + light/dark hex.
// Usage: node scripts/tokens-to-ts.mjs [lightJson] [darkJson]
import { readFile, writeFile } from 'node:fs/promises';

const [lightPath = 'tokens/Light.tokens.json', darkPath = 'tokens/Dark.tokens.json'] = process.argv.slice(2);
const light = JSON.parse(await readFile(lightPath, 'utf8'));
const dark = JSON.parse(await readFile(darkPath, 'utf8'));

function collect(node, path, out) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && value.$type === 'color') {
      out[[...path, key].join('/')] = value;
    } else if (value && typeof value === 'object') {
      collect(value, [...path, key], out);
    }
  }
  return out;
}

const toHex = (v) => {
  const a = v.$value.alpha ?? 1;
  const hex = v.$value.hex.toUpperCase();
  return a < 1 ? hex + Math.round(a * 255).toString(16).padStart(2, '0').toUpperCase() : hex;
};

const l = collect(light, [], {});
const d = collect(dark, [], {});
const entries = Object.keys(l)
  .filter((name) => name.startsWith('chart/') || name.startsWith('system/'))
  .map((name) => {
    const id = l[name].$extensions?.['com.figma.variableId'] ?? '';
    return `  ${JSON.stringify(name)}: { id: ${JSON.stringify(id)}, light: ${JSON.stringify(toHex(l[name]))}, dark: ${JSON.stringify(d[name] ? toHex(d[name]) : toHex(l[name]))} },`;
  });

const hues = Object.keys(light.chart ?? {});
const src = `// AUTO-GENERATED by scripts/tokens-to-ts.mjs — do not edit.
export interface ColorToken { id: string; light: string; dark: string }

export const COLOR_TOKENS: Record<string, ColorToken> = {
${entries.join('\n')}
};

export const CHART_HUES = ${JSON.stringify(hues)} as const;
`;
await writeFile('src/theme/tokens.generated.ts', src);
console.log(`[tokens] ${entries.length} color tokens, ${hues.length} chart hues`);
